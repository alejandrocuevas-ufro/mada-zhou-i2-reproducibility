# Phase D infrastructure: per-replicate reproducible RNG streams with
# common random numbers (CRN) across design cells.
#
# Two properties the Phase C generator did NOT have:
#
#   (P1) NESTING.  The seed of replicate r depends only on (scheme, r) and
#        never on the total number of replicates requested.  A 1000-replicate
#        run therefore contains the 100-replicate run as an exact subset, so
#        results can be extended without discarding earlier work and any
#        single replicate can be re-run in isolation for debugging.
#
#   (P2) COMMON RANDOM NUMBERS.  The latent study effects and the uniforms
#        driving the binomial counts are drawn ONCE per (scheme, replicate)
#        and reused across every rho and every K.  Differences between design
#        cells are therefore not inflated by independent Monte Carlo noise.
#        Counts are generated by inversion (qbinom on a fixed uniform), which
#        is what couples the cells; plain rbinom would break the coupling.
#
# Seeds use L'Ecuyer-CMRG.  The index map is injective over the design range
# (scheme_id < 100, replicate <= 100000): 7919 and 104729 are coprime, so
# 7919*s + 104729*r collides only for (s, r) identical.

RNG_BASE_SEED <- 20261015L
RNG_KIND <- "L'Ecuyer-CMRG"

rng_seed_for <- function(scheme_id, replicate, base_seed = RNG_BASE_SEED) {
  stopifnot(length(scheme_id) == 1L, length(replicate) == 1L,
            scheme_id >= 0, scheme_id < 100, replicate >= 1)
  s <- as.numeric(base_seed) + 7919 * as.numeric(scheme_id) +
    104729 * as.numeric(replicate)
  if (s > .Machine$integer.max)
    stop("Seed index overflowed integer range; reduce replicate count.")
  as.integer(s)
}

# Draw the full latent pool for one (scheme, replicate).  Kmax must be the
# largest K in the design so that smaller K are exact prefixes.
draw_latent_pool <- function(scheme_id, replicate, Kmax,
                             base_seed = RNG_BASE_SEED) {
  seed <- rng_seed_for(scheme_id, replicate, base_seed)
  old_kind <- RNGkind()
  on.exit(RNGkind(old_kind[1], old_kind[2], old_kind[3]), add = TRUE)
  set.seed(seed, kind = RNG_KIND)
  list(seed = seed,
       z1 = rnorm(Kmax), z2 = rnorm(Kmax),
       u_tp = runif(Kmax), u_fp = runif(Kmax))
}

# Build the 2x2 tables for one design cell from a pooled draw.
# mu, SD are the generating logit means / between-study SDs.
# n_disease / n_healthy may be scalars (equal study sizes) or length-Kmax
# vectors (unequal study sizes); vectors are also prefix-stable.
counts_from_pool <- function(pool, K, rho, n_disease, n_healthy, mu, SD) {
  stopifnot(K <= length(pool$z1))
  idx <- seq_len(K)
  nD <- if (length(n_disease) == 1L) rep(n_disease, K) else n_disease[idx]
  nND <- if (length(n_healthy) == 1L) rep(n_healthy, K) else n_healthy[idx]

  z1 <- pool$z1[idx]; z2 <- pool$z2[idx]
  # sqrt((1-|rho|)(1+|rho|)) is stable at |rho| -> 1 and exact at |rho| = 1.
  eta_se <- mu[1] + SD[1] * z1
  eta_fpr <- mu[2] + SD[2] *
    (rho * z1 + sqrt((1 - abs(rho)) * (1 + abs(rho))) * z2)

  # Inversion sampling: the same uniform gives coupled counts across rho.
  TP <- qbinom(pool$u_tp[idx], size = nD, prob = plogis(eta_se))
  FP <- qbinom(pool$u_fp[idx], size = nND, prob = plogis(eta_fpr))
  data.frame(TP = TP, FN = nD - TP, FP = FP, TN = nND - FP)
}

# Unequal study sizes, drawn once per (scheme, replicate) so that they too are
# shared across rho and K.  Log-normal around the scheme median, which is the
# usual shape in diagnostic-accuracy reviews.
draw_study_sizes <- function(scheme_id, replicate, Kmax, median_nD, median_nND,
                             sdlog = 0.6, min_n = 10L,
                             base_seed = RNG_BASE_SEED) {
  seed <- rng_seed_for(scheme_id + 50L, replicate, base_seed)
  old_kind <- RNGkind()
  on.exit(RNGkind(old_kind[1], old_kind[2], old_kind[3]), add = TRUE)
  set.seed(seed, kind = RNG_KIND)
  f <- rlnorm(Kmax, meanlog = 0, sdlog = sdlog)
  list(nD = pmax(min_n, round(median_nD * f)),
       nND = pmax(min_n, round(median_nND * f)))
}
